#!/usr/bin/env python3
# MACDART port of runtime/tools/create_resources.py (originally Python 2).
#
# Bundles resource files (the vmservice Dart sources) into a C++ source file as
# byte-array string literals plus a `ResourcesEntry __<table>_resources_[]`
# table, consumed by bin/vmservice_impl.cc. Only the service isolate uses this;
# a plain `dart script.dart` never reads it, but the symbols must link.
#
# Py3 fixes: bytes iteration (no ord()), `except E as e`, deterministic header.
from __future__ import annotations

import argparse
import os
import re
import sys
import zlib


def make_resources(root_dir, input_files, table_name, compress, no_compress_exts):
    result = ""
    resources = []
    for resource_file in input_files:
        if root_dir and resource_file.startswith(root_dir):
            name = resource_file[len(root_dir):]
        else:
            name = resource_file
        _, ext = os.path.splitext(resource_file)
        do_compress = compress and ext not in no_compress_exts
        with open(resource_file, "rb") as fh:
            data = fh.read()
        if do_compress:
            data = zlib.compress(data)
        sym = re.sub(r"(/|\.|-|\\)", "_", name) + "_"
        result += "// %s\n" % resource_file
        result += "const char " + sym + "[] = {\n   "
        counter = 0
        for byte in data:  # Py3: ints
            result += r" '\x%02x'," % byte
            counter += 1
            if counter == 10:
                result += "\n   "
                counter = 0
        if counter != 0:
            result += "\n   "
        result += " 0\n};\n\n"
        resources.append(("/" + name.replace("\\", "/"), sym, len(data)))

    result += "ResourcesEntry __%s_resources_[] = {\n" % table_name
    for url, sym, length in resources:
        result += '   { "%s", %s, %d },\n' % (url, sym, length)
    result += "   { 0, 0, 0 },\n};\n\n"
    return result


def main(argv) -> int:
    p = argparse.ArgumentParser()
    p.add_argument("--output", required=True)
    p.add_argument("--root_prefix", default="")
    p.add_argument("--outer_namespace", default="dart")
    p.add_argument("--inner_namespace", default=None)
    p.add_argument("--table_name", required=True)
    p.add_argument("--compress", action="store_true")
    p.add_argument("--no_compress_extensions", action="append", default=[".dart"])
    p.add_argument("inputs", nargs="+")
    args = p.parse_args(argv[1:])
    try:
        text = (
            "// Generated by MACDART create_resources.py. Do not edit.\n\n"
            "namespace %s {\n" % args.outer_namespace
        )
        if args.inner_namespace is not None:
            text += "namespace %s {\n" % args.inner_namespace
        text += (
            "\nstruct ResourcesEntry {\n"
            "  const char* path_;\n"
            "  const char* resource_;\n"
            "  int length_;\n"
            "};\n\n"
        )
        text += make_resources(args.root_prefix, args.inputs, args.table_name,
                               args.compress, args.no_compress_extensions)
        if args.inner_namespace is not None:
            text += "}  // namespace %s\n" % args.inner_namespace
        text += "}  // namespace %s\n" % args.outer_namespace
        with open(args.output, "w") as out:
            out.write(text)
        return 0
    except Exception as e:  # noqa: BLE001
        sys.stderr.write("create_resources.py exception\n")
        sys.stderr.write(str(e) + "\n")
        return -1


if __name__ == "__main__":
    sys.exit(main(sys.argv))
